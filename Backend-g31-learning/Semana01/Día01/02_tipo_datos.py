# Datos principales dentro de Python
# int -> Enteros 1 2 0 -5 123456 (sin decimals)
# float -> Flotantes 3.14 2.72 132.213 (con decimales)
# str -> String (cadenas) "Hola mundo"
# bool -> Boleanos True False
# None -> Sin tipo ==> NoneType

print(500, type(500))
print(3.14, type(3.14))
print("Ernesto", type("Ernesto"))
print(True, type(True))
print(None, type(None))